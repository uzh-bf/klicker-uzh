/** A capability contract for public media. Private KB storage is separate. */
export interface MediaUploadRequest {
  ownerId: string
  fileName: string
  contentType: string
}

export interface SignedMediaUpload {
  uploadUrl: string
  uploadHref: string
  uploadHeaders: { name: string; value: string }[]
}

export interface MediaStorage {
  createUpload(request: MediaUploadRequest): Promise<SignedMediaUpload>
}

export const MEDIA_UPLOAD_EXPIRY_SECONDS = 15 * 60

export function validateMediaObject({
  ownerId,
  fileName,
  contentType,
}: MediaUploadRequest) {
  // These identifiers are generated by the application, never user filenames.
  const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
  if (
    !uuid.test(ownerId) ||
    !/^[0-9a-f-]{36}\.(png|jpg|gif|svg|webp|tiff|bmp)$/i.test(fileName) ||
    !uuid.test(fileName.split('.')[0] ?? '')
  ) {
    throw new Error('Media object key is invalid')
  }
  if (!/^image\/(png|jpeg|gif|svg\+xml|webp|tiff|bmp)$/.test(contentType)) {
    throw new Error('Media content type is invalid')
  }
}

export function requireStorageValue(env: NodeJS.ProcessEnv, name: string) {
  const value = env[name]?.trim()
  if (!value) throw new Error(`${name} is required for media storage`)
  return value
}

export function storageUrl(value: string, name: string) {
  let url: URL
  try {
    url = new URL(value)
  } catch {
    throw new Error(`${name} is invalid`)
  }
  let decodedPath: string
  try {
    decodedPath = decodeURIComponent(url.pathname)
  } catch {
    throw new Error(`${name} is invalid`)
  }
  const hasGlob = (value: string) =>
    ['*', '?', '[', ']', '{', '}', '(', ')', '!', '+', '@'].some((character) =>
      value.includes(character)
    )
  const literalIpv6 = url.hostname.startsWith('[') && url.hostname.endsWith(']')
  const local =
    url.hostname === 'localhost' ||
    url.hostname.endsWith('.localhost') ||
    url.hostname === '127.0.0.1' ||
    url.hostname === '[::1]'
  if (
    (url.protocol !== 'https:' && !(url.protocol === 'http:' && local)) ||
    url.username ||
    url.password ||
    url.search ||
    url.hash ||
    (!literalIpv6 && hasGlob(url.hostname)) ||
    hasGlob(decodedPath)
  ) {
    throw new Error(
      `${name} must be an HTTPS URL without credentials, query or fragment (HTTP is allowed for loopback development)`
    )
  }
  let result = url.toString()
  while (result.endsWith('/')) result = result.slice(0, -1)
  return result
}

export function appendObjectPath(base: string, ...segments: string[]) {
  return `${base}/${segments.map(encodeURIComponent).join('/')}`
}
