export async function getChatbotGraphSnapshot(
  args: ChatbotGraphSnapshotArgs
): Promise<ChatbotGraphSnapshot> {
  const nodeLimit = requireLimit(
    args.nodeLimit ?? DEFAULT_NODE_LIMIT,
    'nodeLimit'
  )
  const edgeLimit = requireLimit(
    args.edgeLimit ?? DEFAULT_EDGE_LIMIT,
    'edgeLimit'
  )
  const nodeQuery = `MATCH (n) RETURN n LIMIT ${nodeLimit + 1}`
  const edgeQuery = `MATCH ()-[r]->() RETURN r LIMIT ${edgeLimit + 1}`

  return await withFalkorDBClient(args.client, async (client) => {
    try {
      const [rawNodes, rawEdges] = await Promise.all([
        readChatbotGraph({
          chatbotId: args.chatbotId,
          client,
          query: nodeQuery,
        }),
        readChatbotGraph({
          chatbotId: args.chatbotId,
          client,
          query: edgeQuery,
        }),
      ])
      const parsedNodes = parseNodeRows(rawNodes)
      const visibleNodes = parsedNodes.slice(0, nodeLimit)
      const visibleNodeIds = new Set(visibleNodes.map((node) => node.id))
      const allEdges = parseEdgeRows(rawEdges)
      const parsedEdges = allEdges.filter(
        (edge) =>
          visibleNodeIds.has(edge.source) && visibleNodeIds.has(edge.target)
      )
      const visibleEdges = parsedEdges.slice(0, edgeLimit)

      return {
        nodes: visibleNodes,
        edges: visibleEdges,
        truncated:
          parsedNodes.length > nodeLimit ||
          allEdges.length > edgeLimit ||
          parsedEdges.length > edgeLimit,
        limits: {
          nodeLimit,
          edgeLimit,
        },
      }
    } catch (error) {
      if (isMissingGraphError(error)) {
        return createEmptySnapshot(nodeLimit, edgeLimit)
      }

      throw error
    }
  })
}

export async function seedPrototypeFinanceGraph(
  args: PrototypeFinanceSeedArgs = { chatbotId: BENIBOT_CHATBOT_ID }
): Promise<PrototypeFinanceSeedResult> {
  const chatbotId = args.chatbotId || BENIBOT_CHATBOT_ID
  const graphName = getChatbotGraphName(chatbotId)
  const query = createPrototypeFinanceGraphQuery()

  await withFalkorDBClient(args.client, async (client) => {
    if (args.reset) {
      try {
        await deleteChatbotGraph({ chatbotId, client })
      } catch (error) {
        if (!isMissingGraphError(error)) {
          throw error
        }
      }
    }

    await writeChatbotGraph({ chatbotId, client, query })
  })

  return {
    chatbotId,
    graphName,
    nodeCount: PROTOTYPE_FINANCE_NODES.length,
    relationshipCount: PROTOTYPE_FINANCE_RELATIONSHIPS.length,
  }
}

export function createPrototypeFinanceGraphQuery(): string {
  const nodeVariables = new Map<string, string>()
  const nodeDepths = new Map(
    PROTOTYPE_FINANCE_NODES.map((node) => [node.id, node.depth])
  )
  const nodeStatements = PROTOTYPE_FINANCE_NODES.map((node, index) => {
    const variable = `n${index}`
    nodeVariables.set(node.id, variable)

    const properties = {
      depth: node.depth,
      id: node.id,
      kind: node.kind,
      label: node.label,
      prototype: true,
      summary: node.summary,
      ...(node.formula ? { formula: node.formula } : {}),
    }

    return [
      `MERGE (${variable}:PrototypeFinanceNode {id: ${toCypherValue(node.id)}})`,
      `SET ${toCypherAssignments(variable, properties)}`,
    ].join('\n')
  })

  const relationshipStatements = PROTOTYPE_FINANCE_RELATIONSHIPS.map(
    (relationship, index) => {
      const sourceVariable = requireNodeVariable(
        nodeVariables,
        relationship.source
      )
      const targetVariable = requireNodeVariable(
        nodeVariables,
        relationship.target
      )
      const sourceDepth = requireNodeDepth(nodeDepths, relationship.source)
      const targetDepth = requireNodeDepth(nodeDepths, relationship.target)
      const relationshipVariable = `r${index}`

      return [
        `MERGE (${sourceVariable})-[${relationshipVariable}:${relationship.type}]->(${targetVariable})`,
        `SET ${toCypherAssignments(relationshipVariable, {
          crossLevel: sourceDepth !== targetDepth,
          label: relationship.label,
          prototype: true,
          sourceDepth,
          targetDepth,
        })}`,
      ].join('\n')
    }
  )

  return [
    ...nodeStatements,
    ...relationshipStatements,
    'RETURN count(*) AS seeded',
  ].join('\n')
}

