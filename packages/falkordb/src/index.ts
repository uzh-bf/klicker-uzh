function requireLimit(limit: number, name: string): number {
  if (!Number.isInteger(limit) || limit < 1 || limit > MAX_SNAPSHOT_LIMIT) {
    throw new Error(
      `${name} must be an integer between 1 and ${MAX_SNAPSHOT_LIMIT}`
    )
  }

  return limit
}

function createEmptySnapshot(
  nodeLimit: number,
  edgeLimit: number
): ChatbotGraphSnapshot {
  return {
    nodes: [],
    edges: [],
    truncated: false,
    limits: {
      nodeLimit,
      edgeLimit,
    },
  }
}

function parseNodeRows(result: unknown): ChatbotGraphSnapshotNode[] {
  return getResultRows(result).flatMap((row) => {
    const entity = row[0]
    const id = readEntityString(entity, 'id')
    if (!id) return []

    const labels = readEntityStringList(entity, 'labels')
    const properties = readEntityProperties(entity)

    return [
      {
        id,
        label: getDisplayLabel(properties, labels, id),
        labels,
        properties,
        depth: getOptionalNumber(properties, 'depth'),
        formula: getOptionalString(properties, 'formula'),
        kind: getOptionalString(properties, 'kind'),
        summary: getOptionalString(properties, 'summary'),
      },
    ]
  })
}

function parseEdgeRows(result: unknown): ChatbotGraphSnapshotEdge[] {
  return getResultRows(result).flatMap((row) => {
    const entity = row[0]
    const id = readEntityString(entity, 'id')
    const source = readEntityString(entity, 'src_node')
    const target = readEntityString(entity, 'dest_node')
    const type = readEntityString(entity, 'type')
    if (!id || !source || !target || !type) return []

    const properties = readEntityProperties(entity)

    return [
      {
        id,
        label: getOptionalString(properties, 'label') ?? type,
        source,
        target,
        type,
        properties,
      },
    ]
  })
}

function getResultRows(result: unknown): unknown[][] {
  if (!Array.isArray(result)) return []

  const rows = result[1]
  if (!Array.isArray(rows)) return []

  return rows.filter((row): row is unknown[] => Array.isArray(row))
}

function readEntityString(entity: unknown, field: string): string | undefined {
  const value = readEntityField(entity, field)

  if (typeof value === 'number' || typeof value === 'string') {
    return String(value)
  }

  return undefined
}

function readEntityStringList(entity: unknown, field: string): string[] {
  const value = readEntityField(entity, field)
  if (!Array.isArray(value)) return []

  return value
    .filter((item): item is number | string => {
      return typeof item === 'number' || typeof item === 'string'
    })
    .map((item) => String(item))
}

function readEntityProperties(
  entity: unknown
): Record<string, ChatbotGraphPropertyValue> {
  const value = readEntityField(entity, 'properties')
  if (!Array.isArray(value)) return {}

  return value.reduce<Record<string, ChatbotGraphPropertyValue>>(
    (properties, pair) => {
      if (!Array.isArray(pair) || pair.length < 2) return properties

      const key = pair[0]
      if (typeof key !== 'number' && typeof key !== 'string') return properties

      properties[String(key)] = normalizePropertyValue(pair[1])
      return properties
    },
    {}
  )
}

function readEntityField(entity: unknown, field: string): unknown {
  if (!Array.isArray(entity)) return undefined

  const match = entity.find((entry) => {
    return Array.isArray(entry) && String(entry[0]) === field
  })

  return Array.isArray(match) ? match[1] : undefined
}

function normalizePropertyValue(value: unknown): ChatbotGraphPropertyValue {
  if (
    value === null ||
    typeof value === 'boolean' ||
    typeof value === 'number' ||
    typeof value === 'string'
  ) {
    if (value === 'true') return true
    if (value === 'false') return false

    return value
  }

  return String(value)
}

function getDisplayLabel(
  properties: Record<string, ChatbotGraphPropertyValue>,
  labels: string[],
  id: string
): string {
  return (
    getOptionalString(properties, 'label') ??
    getOptionalString(properties, 'name') ??
    getOptionalString(properties, 'title') ??
    labels[0] ??
    id
  )
}

function getOptionalNumber(
  properties: Record<string, ChatbotGraphPropertyValue>,
  key: string
): number | undefined {
  const value = properties[key]
  return typeof value === 'number' ? value : undefined
}

function getOptionalString(
  properties: Record<string, ChatbotGraphPropertyValue>,
  key: string
): string | undefined {
  const value = properties[key]
  return typeof value === 'string' && value.trim() ? value : undefined
}

function isMissingGraphError(error: unknown): boolean {
  const message = error instanceof Error ? error.message : String(error)

  return /does not exist|not found|unknown graph|empty key/i.test(message)
}

function toCypherAssignments(
  variable: string,
  properties: Record<string, boolean | number | string>
): string {
  return Object.entries(properties)
    .map(([key, value]) => `${variable}.${key} = ${toCypherValue(value)}`)
    .join(', ')
}

function toCypherValue(value: boolean | number | string): string {
  if (typeof value === 'boolean') return value ? 'true' : 'false'
  if (typeof value === 'number') return String(value)

  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

function requireNodeVariable(
  nodeVariables: Map<string, string>,
  nodeId: string
): string {
  const variable = nodeVariables.get(nodeId)
  if (!variable) {
    throw new Error(`Prototype finance graph is missing node ${nodeId}`)
  }

  return variable
}

function requireNodeDepth(nodeDepths: Map<string, number>, nodeId: string) {
  const depth = nodeDepths.get(nodeId)
  if (depth === undefined) {
    throw new Error(`Prototype finance graph is missing node ${nodeId}`)
  }

  return depth
}

async function withFalkorDBClient<T>(
  client: FalkorDBClient | undefined,
  operation: (client: FalkorDBClient) => Promise<T>
): Promise<T> {
  if (client) {
    return await operation(client)
  }

  const createdClient = createFalkorDBClient()

  try {
    return await operation(createdClient)
  } finally {
    await createdClient.quit?.()
  }
}
