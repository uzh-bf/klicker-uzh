import { readFileSync, writeFileSync } from 'node:fs'
import { compile } from 'tailwindcss'
import { artifactCandidates, artifactRootClass } from './starter-style.mjs'

const checkOnly = process.argv.includes('--check')
if (process.argv.slice(2).some((argument) => argument !== '--check'))
  throw new Error('Usage: node generate-styles.mjs [--check]')

const manageTheme = readFileSync(
  new URL('../frontend-manage/src/globals.css', import.meta.url),
  'utf8'
)

function themeToken(name) {
  const match = manageTheme.match(new RegExp(`--${name}:\\s*([^;]+);`))
  if (!match) throw new Error(`Missing Manage theme token --${name}`)
  return match[1].trim()
}

const blue = themeToken('color-uzh-blue')
const primary = themeToken('theme-color-primary')
const grey20 = themeToken('color-uzh-grey-20')
const grey60 = themeToken('color-uzh-grey-60')
const surface = themeToken('background')
const foreground = themeToken('foreground')
if (blue.toLowerCase() !== primary.toLowerCase())
  throw new Error('The canonical UZH primary color no longer matches UZH blue')

const compilerInput = `
@theme inline {
  --font-sans: "Source Sans 3", "Source Sans Pro", ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;
  --color-black: ${foreground};
  --color-white: ${surface};
  --color-uzh-blue: ${blue};
  --color-uzh-grey-20: ${grey20};
  --color-uzh-grey-60: ${grey60};
  --spacing: 0.25rem;
  --breakpoint-sm: 40rem;
  --container-2xl: 42rem;
  --text-sm: 0.875rem;
  --text-sm--line-height: calc(1.25 / 0.875);
  --text-lg: 1.125rem;
  --text-lg--line-height: calc(1.75 / 1.125);
  --text-2xl: 1.5rem;
  --text-2xl--line-height: calc(2 / 1.5);
  --text-3xl: 1.875rem;
  --text-3xl--line-height: calc(2.25 / 1.875);
  --font-weight-medium: 500;
  --font-weight-semibold: 600;
  --leading-tight: 1.25;
  --leading-relaxed: 1.625;
  --radius-md: 0.375rem;
  --radius-lg: 0.5rem;
}
@tailwind utilities;
`

const { build } = await compile(compilerInput, {
  base: new URL('.', import.meta.url).pathname,
  from: new URL('./starter-style.css', import.meta.url).pathname,
  polyfills: 0,
})

const compiled = build(artifactCandidates).replace(
  /^\/\*!.*?\*\/\n/,
  '/*! Tailwind CSS 4.3.3 | MIT License */\n'
)
const propertyStart = compiled.indexOf('\n@property ')
const utilityRules =
  propertyStart === -1 ? compiled : compiled.slice(0, propertyStart)
const propertyRules =
  propertyStart === -1 ? '' : compiled.slice(propertyStart + 1)

function scopeRule(line) {
  const selector = line.match(/^(\s*)(\.[^{}]+?)\s*\{\s*$/)
  if (!selector) {
    if (/^\s*\./.test(line) && line.trimEnd().endsWith('{'))
      throw new Error('Unsupported generated selector: ' + line.trim())
    return line
  }
  const scoped = selector[2]
    .split(',')
    .flatMap((part) => {
      const value = part.trim()
      return [`.${artifactRootClass}${value}`, `.${artifactRootClass} ${value}`]
    })
    .join(', ')
  return `${selector[1]}${scoped} {`
}

const scopedUtilities = utilityRules
  .split('\n')
  .map(scopeRule)
  .join('\n')
  .trimEnd()

const stylesheet = `/* Generated by generate-styles.mjs from Tailwind CSS 4.3.3 and the canonical Manage UZH theme. */
${propertyRules.trim()}
${scopedUtilities}
:where(.${artifactRootClass}) {
  box-sizing: border-box;
}
:where(.${artifactRootClass}) *,
:where(.${artifactRootClass}) *::before,
:where(.${artifactRootClass}) *::after {
  box-sizing: border-box;
}
:where(.${artifactRootClass}) h1 {
  margin: 0;
  font-size: inherit;
  font-weight: inherit;
  line-height: inherit;
}
:where(.${artifactRootClass}) input {
  min-width: 0;
  color: inherit;
  font: inherit;
}
:where(.${artifactRootClass}) :focus-visible {
  outline: 2px solid ${blue};
  outline-offset: 2px;
}
`

if (/https?:\/\//.test(stylesheet))
  throw new Error('Generated artifact styles must not reference a network URL')
if (stylesheet.includes('</style'))
  throw new Error(
    'Generated artifact styles cannot contain a closing style tag'
  )

const output = new URL('./styles.css', import.meta.url)
if (checkOnly) {
  if (readFileSync(output, 'utf8') !== stylesheet)
    throw new Error('artifact-pilot/styles.css is stale; regenerate it')
  console.log('artifact-pilot/styles.css is current')
} else {
  writeFileSync(output, stylesheet)
  console.log(
    `wrote artifact-pilot/styles.css (${Buffer.byteLength(stylesheet)} bytes)`
  )
}
